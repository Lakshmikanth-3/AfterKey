import fs from 'node:fs';
import {getAddress,parseEventLogs} from 'viem';
import {clientFor,DEFAULT_RPC,serialize} from '../src/engine';
import {WORKSPACE_OWNER} from '../src/workspace';
import {contract,nextSetupAction,resolverProxySalt,type SetupState} from '../src/ens/protocol';
import {factoryAbi,ensAbi} from '../src/ens/abi';
import {SET_DATA} from '../src/ens/roles';
const c=clientFor(DEFAULT_RPC),height=BigInt(process.argv[2]||'12079630');
const block=await c.getBlock({blockNumber:height,includeTransactions:true});
const tx=block.transactions.find(t=>typeof t!=='string'&&t.from.toLowerCase()===WORKSPACE_OWNER.toLowerCase()&&t.to?.toLowerCase()===contract('VerifiableFactory').toLowerCase());
if(!tx||typeof tx==='string')throw new Error('No owner factory transaction at block');
const receipt=await c.getTransactionReceipt({hash:tx.hash});
if(receipt.status!=='success'||receipt.blockHash!==block.hash)throw new Error('Receipt not canonical and successful');
const logs=parseEventLogs({abi:factoryAbi,eventName:'ProxyDeployed',logs:receipt.logs});
const deployed=logs.find(l=>l.address.toLowerCase()===contract('VerifiableFactory').toLowerCase()&&l.args.sender.toLowerCase()===WORKSPACE_OWNER.toLowerCase()&&l.args.implementation.toLowerCase()===contract('PermissionedResolverImpl').toLowerCase());
if(!deployed)throw new Error('Expected owner resolver deployment event missing');
const resolver=getAddress(deployed.args.proxyAddress);
const canWriteData=await c.readContract({address:resolver,abi:ensAbi,functionName:'hasRootRoles',args:[SET_DATA|(SET_DATA<<128n),WORKSPACE_OWNER]});
if(!canWriteData)throw new Error('Resolver missing owner data setter/admin roles');
const state:SetupState={parent:'manager.eth',label:'afterkey-release',key:'description',textValue:'Owner-reviewed configuration releases for treasury workflows.',resolverSalt:String(resolverProxySalt(WORKSPACE_OWNER,2n)),resolver,transactions:[]};
const next=await nextSetupAction(state,WORKSPACE_OWNER,DEFAULT_RPC);
const proof={block:String(height),transactionHash:tx.hash,resolver,ownerDataSetterAndAdmin:canWriteData,nextAction:next};
fs.writeFileSync('docs/release-repair-resolver-proof.json',serialize(proof)+'\n');
console.log(serialize(proof));
